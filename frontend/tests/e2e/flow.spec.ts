import { expect, test } from "@playwright/test"

test("путь от приветствия до плана и чата", async ({ page }) => {
  await page.goto("/welcome")
  await page.getByRole("link", { name: "Войти" }).click()
  await page.getByRole("textbox", { name: "Логин" }).fill("vasek")
  await page.getByRole("textbox", { name: "Пароль" }).fill("secret-secret")
  await page.getByRole("checkbox").check()
  await page.getByRole("button", { name: "Войти" }).click()
  await page.getByTestId("next-step").getByText("Заполнить профиль").click()
  await page.getByLabel("Кличка").fill("Рекс")
  await page.getByRole("radio", { name: "1–3 года" }).click()
  await page.getByRole("radio", { name: "мальчик" }).click()
  await page.getByRole("button", { name: "Выберите дату" }).click()
  await page.getByRole("button", { name: "1", exact: true }).click()
  await page.getByRole("radio", { name: "из приюта" }).click()
  await page.getByRole("radio", { name: "да", exact: true }).click()
  await page.getByRole("button", { name: "Готово" }).click()
  await page.getByTestId("next-step").getByText("Получить план").click()
  await page.getByRole("button", { name: "Заполнить анкету" }).click()
  await page.getByRole("radio", { name: "7" }).click()
  await page.getByRole("button", { name: "Далее" }).click()
  await expect(page.getByRole("heading", { name: "Сервис в разработке" })).toBeVisible()
  await page.getByRole("button", { name: "Главная" }).click()
  await expect(page.getByRole("heading", { name: "Рекс" })).toBeVisible()
  await expect(page.getByTestId("next-step")).toHaveCount(0)
  await page.getByRole("button", { name: "Чат" }).click()
  await page.getByLabel("Сообщение").fill("как гулять с собакой")
  await page.getByRole("button", { name: "Отправить" }).click()
  await expect(page.getByText(/По материалам/)).toBeVisible()
})
